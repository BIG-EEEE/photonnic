<?php
/*
 * One-time setup on the server: creates config.php (VAPID key pair, salt, database path)
 * and the data folder, both readable by this account only. Refuses to overwrite an
 * existing config, because a new key pair would break every existing subscription.
 *
 *   php setup.php https://photonnic.destinyfamily.org
 */
declare(strict_types=1);
require __DIR__ . '/lib.php';

$file = __DIR__ . '/config.php';
if (is_file($file)) { fwrite(STDERR, "config.php already exists; not replacing it.\n"); exit(1); }
$subject = $argv[1] ?? '';
if (!preg_match('#^(https://|mailto:)#', $subject)) { fwrite(STDERR, "usage: php setup.php https://your.site\n"); exit(1); }

$data = __DIR__ . '/data';
if (!is_dir($data)) mkdir($data, 0700, true);
chmod($data, 0700);

$key = ec_new();
openssl_pkey_export($key, $pem, null, ssl_args());
$config = [
    'vapid_public' => b64url(ec_raw_public($key)),
    'vapid_private_pem' => $pem,
    'subject' => $subject,
    'db' => $data . '/push.sqlite',
    'ip_salt' => bin2hex(random_bytes(16)),
    'transport' => 'http',
];
file_put_contents($file, "<?php\n// Generated by setup.php. Secret: never commit, never copy into the web root.\nreturn " . var_export($config, true) . ";\n");
chmod($file, 0600);
db(); // create the tables
chmod($config['db'], 0600);
echo "Created config.php and data/. Public key: {$config['vapid_public']}\n";
